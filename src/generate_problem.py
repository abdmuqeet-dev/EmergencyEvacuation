"""Turn a scenario + the building graph into a PDDL problem for pddl/domain.pddl.

Scenario keys used here:
  name                   problem name
  groups                 [{"id": "g1", "location": "<node id>", "mobility_impaired": false, "size": 20}]
  trust_uncertain_exits  count exits flagged uncertain as real exits (default false)
  refuges                extra refuge node ids on top of the elevator lobbies
  crowding               {"stair_capacity": K, "waves": N}: limit each stair segment to K groups per
                         wave (K defaults to 3, N is computed). Omit to ignore stair capacity.
See rules.py for the emergency keys.
"""
import re

import graph
import rules

ID =re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")


def _validate_groups(b, scn):
    groups = scn.get("groups") or []
    if not groups:
        raise ValueError("scenario needs at least one group")
    seen = set()
    for g in groups:
        gid, loc = g.get("id"), g.get("location")
        if not gid or not ID.match(gid) or gid in seen:
            raise ValueError("bad or duplicate group id %r" % gid)
        seen.add(gid)
        if not b.has(loc):
            raise ValueError("group %s: unknown location %r" % (gid, loc))
        if b.nodes[loc]["type"] in ("exit", "assembly"):
            raise ValueError("group %s starts at an exit; it is already out" % gid)
    return groups


DEFAULT_STAIR_CAPACITY = 3  # groups per stair segment per wave (placeholder, assumption A4)


def crowding_config(b, scn, groups):
    """Return (capacity, n_waves) when the scenario asks for crowding, else None.

    Scenario key "crowding": {"stair_capacity": K, "waves": N}. Waves default to enough for the
    tallest descent plus every group waiting its turn, plus slack.
    """
    cfg = scn.get("crowding")
    if not cfg:
        return None
    cap = int(cfg.get("stair_capacity", DEFAULT_STAIR_CAPACITY))
    if cap < 1:
        raise ValueError("crowding.stair_capacity must be at least 1")
    top = max(graph.FLOOR_ORDER.index(b.floor(g["location"])) for g in groups)
    n_waves = int(cfg.get("waves", top + -(-len(groups) // cap) + 3))
    return cap, n_waves


def crowding_facts(b, cap, n_waves, used_slots=frozenset()):
    """(objects, init facts) for waves and slots: cap slots per stair segment per wave.

    Slot names depend only on the building, cap and n_waves, so a later group can be planned
    against the slots earlier groups already took (used_slots stay out of the free pool).
    """
    waves = ["w%d" % i for i in range(n_waves)]
    objs = [" ".join(waves) + " - wave"]
    facts = ["    (crowding)"]
    facts += ["    (wave-next %s %s)" % (a, c) for a, c in zip(waves, waves[1:])]
    slots, n = [], 0
    for up, lo in b.stairs_down():
        for w in waves[:-1]:  # the last wave has no successor, so nothing can be descended in it
            for _ in range(cap):
                slots.append("slot%d" % n)
                free = "" if ("slot%d" % n) in used_slots else " (slot-free slot%d)" % n
                facts.append("    (slot-of slot%d %s %s %s)%s" % (n, up, lo, w, free))
                n += 1
    objs.append(" ".join(slots) + " - slot")
    return objs, facts


def build_problem(b, scn, rule_result=None, used_slots=frozenset(), shaking=None):
    """PDDL text for the scenario. used_slots / shaking are for planning one group at a time:
    slots already taken stay out of the free pool, and shaking=False drops the global (shaking)
    fact once it has been dealt with. Leave both at their defaults for a normal problem."""
    r = rule_result or rules.apply(scn, b)
    groups = _validate_groups(b, scn)
    crowd = crowding_config(b, scn, groups)
    exits = b.exits(bool(scn.get("trust_uncertain_exits")))
    refuges = set(b.refuges()) | set(scn.get("refuges", []))
    for i in refuges:
        if not b.has(i):
            raise ValueError("refuges: unknown node id %r" % i)

    name = re.sub(r"[^A-Za-z0-9_]", "_", scn.get("name", "scenario"))
    out = ["; generated by src/generate_problem.py - do not edit",
           "; " + "; ".join(r.notes) if r.notes else "; no emergency notes",
           "(define (problem %s)" % name,
           "  (:domain evac)",
           "  (:objects",
           "    " + " ".join(b.locations()) + " - location",
           "    " + " ".join(g["id"] for g in groups) + " - group"]
    crowd_facts = []
    if crowd:
        objs, crowd_facts = crowding_facts(b, *crowd, used_slots=used_slots)
        out += ["    " + o for o in objs]
        crowd_facts += ["    (group-time %s w0)" % g["id"] for g in groups]
    out[-1] += ")"
    out += ["  (:init",
            "    (= (total-cost) 0)"] + crowd_facts
    for a, c in b.walk_pairs():
        out.append("    (connected %s %s) (connected %s %s)" % (a, c, c, a))
    for up, lo in b.stairs_down():
        out.append("    (stairs-down %s %s)" % (up, lo))
    for a, c in b.elevator_links():
        out.append("    (elevator-link %s %s)" % (a, c))
    for e in exits:
        out.append("    (exit %s)" % e)
    for i in sorted(refuges):
        out.append("    (refuge %s)" % i)
    for i in sorted(r.blocked):
        out.append("    (blocked %s)" % i)
    if r.directed_by_responders:
        out.append("    (directed-by-responders)")
    if r.shelter_in_place_ok:
        out.append("    (shelter-in-place-ok)")
    if (r.shaking if shaking is None else shaking):
        out.append("    (shaking)")
    for g in groups:
        out.append("    (at %s %s)" % (g["id"], g["location"]))
        if g.get("mobility_impaired"):
            out.append("    (mobility-impaired %s)" % g["id"])
    out.append("  )")
    out.append("  (:goal (and " + " ".join("(safe %s)" % g["id"] for g in groups) + "))")
    out.append("  (:metric minimize (total-cost)))")
    return "\n".join(out) + "\n"
